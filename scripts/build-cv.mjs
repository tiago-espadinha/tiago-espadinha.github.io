#!/usr/bin/env node
/**
 * Writes the CV's LaTeX for one language from the site's content, so the
 * page and the PDF never disagree.
 *
 *   node scripts/build-cv.mjs en cv/build/cv-en.tex
 *
 * Normally run through `npm run cv` (make -C cv), which then builds the PDF
 * with cv/resume.cls (style) and cv/preamble.tex (page setup, \entry).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import { cv } from "../content/cv.js";
import * as content from "../content/index.js";
import { LOCALES, translate } from "../js/lib/i18n.js";

const BABEL = { en: "english", pt: "portuguese" };

const [lang, out] = process.argv.slice(2);
if (!LOCALES.includes(lang) || !out) {
  console.error(
    `Usage: node scripts/build-cv.mjs <${LOCALES.join("|")}> <out.tex>`,
  );
  process.exit(1);
}

/** Text in this CV's language, escaped for LaTeX. */
const tx = (text, params) => escape(translate(text, lang, params));

/**
 * Escape LaTeX's special characters, then turn the content's light markup
 * into LaTeX: **bold**, *italic*, and a blank line for a new paragraph.
 */
const SPECIAL = {
  "\\": "\\textbackslash{}",
  "{": "\\{",
  "}": "\\}",
  "&": "\\&",
  "%": "\\%",
  $: "\\$",
  "#": "\\#",
  _: "\\_",
  "~": "\\textasciitilde{}",
  "^": "\\textasciicircum{}",
};

function escape(text) {
  if (text === "LaTeX") return "\\LaTeX{}";
  return text
    .replace(/[\\{}&%$#_~^]/g, (c) => SPECIAL[c])
    .replace(/\*\*(.+?)\*\*/g, "\\textbf{$1}")
    .replace(/\*(.+?)\*/g, "\\textit{$1}")
    .replace(/\n\s*\n/g, "\\par\\vspace{1ex}\n");
}

const dates = ({ from, to }) =>
  to === null
    ? tx(cv.dates.ongoing, { from })
    : tx(cv.dates.range, { from, to });

const list = (items) => items.map((item) => tx(item)).join(", ");

const section = (heading, body) =>
  `\\begin{rSection}{${tx(heading)}}\n\n${body}\n\n\\end{rSection}`;

function header() {
  const github = content.contact.links.find((link) => link.icon === "github");
  const site = github.url.replace(/^https?:\/\//, "");
  return [
    `\\name{${escape(cv.name)}}`,
    `\\address{${escape(cv.phone)} \\\\ ${tx(cv.city)}}`,
    `\\address{%`,
    `  \\href{mailto:${content.contact.email}}{${escape(content.contact.email)}} \\\\`,
    `  \\href{${github.url}}{${escape(site)}}%`,
    `}`,
  ].join("\n");
}

function experience() {
  return content.work
    .map(
      (job) =>
        `\\entry{${tx(job.title)}}{${dates(job)}}{%\n  ${tx(job.cv ?? job.description)}}`,
    )
    .join("\n\n");
}

function projects() {
  return content.projects
    .map(
      (project) =>
        `\\entry{\\href{${project.liveUrl}}{${escape(project.title)}}}{${list(project.cvStack ?? project.stack)}}{%\n  ${tx(project.cv ?? project.summary)}}`,
    )
    .join("\n\n");
}

function education() {
  return content.education
    .map((degree) => {
      const text = tx(degree.cv ?? degree.description);
      const body = [escape(degree.school), text].filter(Boolean).join(". ");
      return `\\entry{${tx(degree.title)}}{${dates(degree)}}{%\n  ${body}}`;
    })
    .join("\n\n");
}

function skills() {
  const rows = [
    ...content.toolkit.filter((group) => group.onCv !== false),
    ...cv.skills,
  ].map((group) => `${tx(group.label)} & ${list(group.items)}`);
  return [
    "\\begin{tabular}{@{} >{\\bfseries}l @{\\hspace{6ex}} l}",
    rows.join(" \\\\[0.6ex]\n"),
    "\\end{tabular}",
  ].join("\n");
}

function workshops() {
  const items = cv.workshops.map((item) => `  \\item ${tx(item)}`);
  return [
    "\\begin{itemize}\\setlength{\\itemsep}{0pt}",
    ...items,
    "\\end{itemize}",
  ].join("\n");
}

const tex = `% Generated by scripts/build-cv.mjs from content/. Edit the content, not this file.
\\documentclass{resume}
\\usepackage[${BABEL[lang]}]{babel}
\\input{preamble}
${header()}

\\begin{document}

${section(cv.headings.experience, experience())}

${section(cv.headings.projects, projects())}

${section(cv.headings.education, education())}

${section(cv.headings.skills, skills())}

${section(cv.headings.workshops, workshops())}

\\end{document}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, tex);
